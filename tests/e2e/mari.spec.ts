import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { resolve } from "node:path";
import { adminCredentials } from "./admin-credentials";
test("páginas públicas, navegação e acessibilidade", async ({ page }, info) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  for (const path of ["/", "/buscar", "/contato", "/minha-selecao", "/privacidade", "/admin/login"]) {
    expect((await page.goto(path))?.status()).toBe(200);
    await expect(page.locator("h1")).toHaveCount(1);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await expect(page.locator("body")).not.toContainText("Adim");
  }
  await page.goto("/");
  const accessibility = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa"]).analyze();
  expect(accessibility.violations).toEqual([]);
  await page.screenshot({ path: `docs/mari/inicio-${info.project.name}.png`, fullPage: true });
  if (info.project.name === "mobile") { await page.getByRole("button", { name: "Abrir menu" }).click(); await page.getByRole("navigation", { name: "Menu mobile" }).getByRole("link", { name: "Imóveis", exact: true }).click(); await expect(page).toHaveURL(/buscar/); }
  expect(errors).toEqual([]);
});
test("jornada real: cadastro sem SMS, fotos, filtros, seleção, CRM e editor", async ({ page, browser, baseURL }, info) => {
  test.setTimeout(180000);
  const origin = baseURL!;
  const headers = { origin };
  const unique = `${info.project.name}-${Date.now()}`;
  const phone = `479${String(Date.now()).slice(-8)}`;
  const title = `Imóvel de teste automatizado ${unique}`;
  let propertyId = "", fieldId = "", leadId = "", imageId = "";
  let initialContent: Record<string, unknown> | null = null;
  const visitor = await browser.newContext({ viewport: info.project.use.viewport, extraHTTPHeaders: headers, httpCredentials: info.project.use.httpCredentials });
  const guest = await visitor.newPage();
  const admin = adminCredentials();
  await page.goto("/admin/login");
  await page.getByLabel("E-mail", { exact: true }).fill(admin.email);
  await page.getByLabel("Senha", { exact: true }).fill(admin.password);
  await page.getByRole("button", { name: "Entrar no painel" }).click();
  await expect(page).toHaveURL(/\/admin$/);
  try {
    const fieldResponse = await page.request.post("/api/admin/fields", { headers, data: { label: `Vista de teste ${unique}`, type: "boolean", required: false, public: true, filterable: true, options: [] } });
    expect(fieldResponse.ok()).toBe(true); fieldId = (await fieldResponse.json()).id;
    await page.goto("/admin?tab=properties");
    await page.getByRole("button", { name: "Cadastrar imóvel" }).click();
    await page.getByLabel("Título do anúncio", { exact: true }).fill(title);
    await page.getByLabel("Bairro", { exact: true }).fill("Bairro de teste");
    await page.getByLabel("Descrição do anúncio").fill("Registro temporário criado exclusivamente pelo teste automatizado. Será removido ao concluir.");
    await page.getByLabel("Endereço completo (somente administração)").fill("ENDERECO-PRIVADO-NAO-EXIBIR");
    await page.getByLabel("Valor do anúncio (R$)").fill("2500000");
    await page.getByRole("combobox", { name: "Status", exact: true }).selectOption("published");
    await page.getByLabel("Destacar na página inicial").check();
    await page.getByRole("combobox", { name: `Vista de teste ${unique}`, exact: true }).selectOption("true");
    await page.locator('input[type="file"]').setInputFiles(resolve("public/images/living.webp"));
    await expect(page.locator(".image-editor-item")).toHaveCount(1);
    await page.getByRole("button", { name: "Salvar imóvel", exact: true }).click();
    await expect(page.getByText("Imóvel salvo com sucesso.")).toBeVisible();
    const listings = await (await page.request.get(`/api/admin/properties?q=${encodeURIComponent(unique)}`)).json();
    const property = listings[0]; propertyId = property.id; imageId = property.images[0].id;
    const publicItem = await (await visitor.request.get(`/api/properties/${property.slug}`)).json();
    expect(JSON.stringify(publicItem)).not.toContain("ENDERECO-PRIVADO");
    expect((await visitor.request.get(`/media/${property.images[0].key}`)).headers()["content-type"]).toContain("image/webp");
    const url = `/buscar?q=${encodeURIComponent(unique)}&field_${fieldId}=true`;
    const clientReady = guest.waitForResponse(response => new URL(response.url()).pathname === "/api/client" && response.ok());
    await guest.goto(url);
    await clientReady;
    await expect(guest.locator(".listing-card:visible")).toHaveCount(1);
    await expect(async () => { await guest.locator(".listing-card:visible").scrollIntoViewIfNeeded(); }).toPass({ timeout: 10000 });
    const scroll = await guest.evaluate(() => scrollY);
    await guest.getByRole("link", { name: `Conhecer ${title}` }).click();
    await expect(guest.getByRole("dialog", { name: "Conheça este imóvel" })).toBeVisible();
    await expect(guest).toHaveURL(new RegExp(property.slug));
    const message = new URL((await guest.locator('.price-panel a[href^="https://wa.me/"]').getAttribute("href"))!).searchParams.get("text");
    expect(message).toContain(property.code); expect(message).toContain(`/imovel/${property.slug}`);
    await guest.keyboard.press("Escape");
    await expect(guest).toHaveURL(new RegExp(`field_${fieldId}=true`));
    expect(Math.abs((await guest.evaluate(() => scrollY)) - scroll)).toBeLessThan(5);
    await guest.getByRole("button", { name: `Adicionar ${property.code} à seleção` }).click();
    await guest.getByLabel("Primeiro nome", { exact: true }).fill("Teste");
    await guest.getByLabel("Telefone com WhatsApp").fill(phone);
    await guest.getByRole("checkbox").check();
    await guest.getByRole("button", { name: "Criar minha seleção", exact: true }).click();
    await expect(guest.getByRole("dialog")).not.toBeVisible();
    const selected = await (await visitor.request.get("/api/client")).json();
    expect(selected.items.map((p: { id: string }) => p.id)).toContain(propertyId);
    await guest.reload();
    await guest.goto("/minha-selecao");
    await expect(guest.getByText("1 imóvel selecionado", { exact: true })).toBeVisible();
    await expect(guest.locator(".cri-hero-title")).toContainText(title.toUpperCase());
    const crm = await (await page.request.get(`/api/admin/leads?q=${phone}`)).json();
    leadId = crm[0].id; expect(crm).toHaveLength(1); expect(crm[0].selection._count.items).toBe(1);
    const outsider = await browser.newContext({ extraHTTPHeaders: headers, httpCredentials: info.project.use.httpCredentials });
    const shared = await (await outsider.request.get(`/api/shared/${selected.publicToken}`)).json();
    expect(Object.keys(shared).sort()).toEqual(["items", "title"]); expect(JSON.stringify(shared)).not.toContain(phone);
    expect((await outsider.request.delete(`/api/selection/${propertyId}`, { data: {} })).status()).toBe(401);
    expect((await outsider.request.get("/api/admin/leads")).status()).toBe(401);
    const duplicate = await outsider.request.post("/api/client/register", { data: { firstName: "Outro", phone, consent: true, propertyId } });
    expect((await duplicate.json()).recoveryRequired).toBe(true);
    expect(await (await outsider.request.get("/api/client")).json()).toBeNull();
    expect((await outsider.request.post("/api/client/otp", { data: { phone } })).status()).toBe(404);
    expect((await (await visitor.request.get("/api/client")).json()).items).toHaveLength(1);
    expect((await visitor.request.post("/api/contact", { data: { consent: true, propertyId, message: "Contato automatizado de teste" } })).ok()).toBe(true);
    const detail = await (await page.request.get(`/api/admin/leads/${leadId}`)).json(); expect(detail.requests).toHaveLength(1);
    expect((await page.request.post("/api/admin/properties", { headers: { origin: "https://malicioso.invalid" }, data: {} })).status()).toBe(403);
    const malicious = await page.request.post("/api/admin/upload", { headers, multipart: { file: { name: "malicioso.svg", mimeType: "image/svg+xml", buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>') } } }); expect(malicious.status()).toBe(400);
    await outsider.close();
    const settings = await (await page.request.get("/api/admin/settings")).json(); initialContent = settings.content.published;
    await page.goto("/admin?tab=editor");
    await page.getByRole("button", { name: "Banner principal", exact: true }).click();
    const newTitle = `Título temporário de teste ${unique}`;
    await page.getByRole("textbox", { name: "Título do banner", exact: true }).fill(newTitle);
    await expect(page.frameLocator('iframe[title="Prévia editável do site"]').getByRole("heading", { name: newTitle, exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Salvar rascunho", exact: true }).click();
    await expect(page.getByText("Rascunho salvo.", { exact: false })).toBeVisible();
    await guest.goto("/"); await expect(guest.locator("h1")).not.toHaveText(newTitle);
    await page.getByRole("button", { name: "Publicar alterações", exact: true }).click();
    await expect(page.getByText("Alterações publicadas.", { exact: false })).toBeVisible();
    await guest.reload(); await expect(guest.locator("h1")).toHaveText(newTitle);
    await page.screenshot({ path: `docs/mari/editor-${info.project.name}.png`, fullPage: true });
    await page.goto("/admin?tab=leads"); await page.screenshot({ path: `docs/mari/crm-${info.project.name}.png`, fullPage: true });
  } finally {
    if (initialContent) { const settings = await (await page.request.get("/api/admin/settings")).json(); await page.request.post("/api/admin/content", { headers, data: { action: "publish", content: initialContent, revision: settings.content.revision } }); }
    if (propertyId) await page.request.delete(`/api/admin/properties/${propertyId}`, { headers, data: {} });
    if (imageId) await page.request.delete(`/api/admin/media/${imageId}`, { headers, data: {} });
    if (fieldId) await page.request.delete(`/api/admin/fields/${fieldId}`, { headers, data: {} });
    if (leadId) await page.request.delete(`/api/admin/leads/${leadId}`, { headers, data: {} });
    await visitor.close();
  }
});
